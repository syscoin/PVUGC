#!/usr/bin/env python3
"""Deterministic finite sanity checks for Run 647's hidden-XOR-period mixer.

No cryptographic implementation; the reversible gate mixer is finite and the quantum samples are simulated from the proved
Hadamard-output probability distribution, not generated by quantum hardware.
"""
import hashlib
import itertools
import json
import random
from collections import Counter
from fractions import Fraction

START_SHA = '93937ee77f20540fbd23c2ce851cc99c8e016f5e'
SEED = 20261019
checks = 0
fixtures = 0
simulations = 0
mixer_gates_total = 0

def check(ok, message='failed'):
    global checks
    checks += 1
    if not ok:
        raise AssertionError(message)

def dot(a,b):
    return (a & b).bit_count() & 1

def quotient(x,k,b):
    # Delete lowest 1-bit pivot after eliminating the period from every other coordinate.
    pivot = (k & -k).bit_length()-1
    pivot_value = (x >> pivot) & 1
    result = 0
    outbit = 0
    for j in range(b):
        if j == pivot:
            continue
        bit = ((x >> j) & 1) ^ ((((k >> j) & 1) & pivot_value))
        result |= bit << outbit
        outbit += 1
    return result

def public_reversible_mixer(n, rng):
    """PPT-sized list of NOT/CNOT/Toffoli gates, applied to n-bit data."""
    gates = []
    for _ in range(max(8,8*n*n)):
        target = rng.randrange(n)
        available = [i for i in range(n) if i != target]
        kind = rng.choice([0,1,2] if n >= 3 else ([0,1] if n >= 2 else [0]))
        controls = rng.sample(available,kind)
        gates.append((target,controls))
    return gates

def evaluate_reversible(gates, x):
    for target, controls in gates:
        if all(((x >> c)&1)==1 for c in controls):
            x ^= 1 << target
    return x

def nullity_one(rows, b):
    candidates = [s for s in range(1,1<<b) if all(dot(s,y)==0 for y in rows)]
    return candidates

for b in range(2,8):
    N = 1<<b
    for k in range(1,N):
        fixtures += 1
        rng = random.Random(SEED + b*100000 + k)
        gates = public_reversible_mixer(b-1,rng)
        mixer_gates_total += len(gates)
        permutation = [evaluate_reversible(gates,x) for x in range(N//2)]
        check(sorted(permutation)==list(range(N//2)), 'local reversible mixer must permute')
        f = [permutation[quotient(x,k,b)] for x in range(N)]
        counts = Counter(f)
        check(len(counts)==N//2,'range size')
        check(set(counts.values())=={2},'2-to-1 fibers')
        check(all(f[x]==f[x^k] for x in range(N)),'period law')
        # Exhaustively assert the exact collision relation, including x = x'.
        for x in range(N):
            check(all((f[x] == f[z]) == (z == x or z == (x^k)) for z in range(N)), 'no other collisions')
        # A quantum coherent query, output measurement, and Hadamard transform.
        # For a coset {x,x xor k}, P(y) = [(sign(x.y)+sign((x^k).y))^2]/2^(b+1).
        x = rng.randrange(N)
        distribution = []
        for y in range(N):
            numerator = ((-1)**dot(x,y)) + ((-1)**dot(x^k,y))
            p = Fraction(numerator*numerator, 1 << (b+1))
            expected = Fraction(1, 1 << (b-1)) if dot(k,y)==0 else Fraction(0,1)
            check(p==expected, 'Hadamard distribution')
            distribution.append(p)
        check(sum(distribution)==1, 'probabilities normalize')
        support = [y for y,p in enumerate(distribution) if p > 0]
        check(len(support)==N//2, 'orthogonal samples uniform')
        check(all(dot(k,y)==0 for y in support), 'orthogonality')
        # O(b+security) independent quantum samples recover the unique nonzero period.
        for trial in range(6):
            samples = [rng.choice(support) for _ in range(b+20)]
            candidates = nullity_one(samples,b)
            check(candidates == [k], 'period recovered')
            simulations += 1
        # Classical outsider need not be given either preimage or random permutation.
        # An ideal black-box hidden-period oracle remains broken by Simon's equations.
        check(quotient(x,k,b)==quotient(x^k,k,b), 'kernel check')

# Exact illustrative bounds, distinct valid states and randomized public coins.
security_examples=[]
for b,d in [(128,0),(256,0),(256,64),(256,128),(384,128),(512,256)]:
    # M=2^d distinct marked states; QPT Grover exponent (b-d)/2 if generic search is available.
    security_examples.append({'state_bits':b,'distinct_marked_states_log2':d,
       'grover_log2_queries':(b-d)/2,'classical_log2_random_tries':b-d})
    check(b>=d and (b-d)>=0)

# Each of n=b+128 Simon equations is uniformly distributed in k-perp;
# union bound on another nonzero candidate period: (2^(b-1)-1)*2^(-n).
for b in (128,256,384):
    n=b+128
    exact_failure_union=Fraction((1 << (b-1))-1,1 << n)
    check(exact_failure_union < Fraction(1,1 << 129))

result={'run':'647','start_sha':START_SHA,'seed':SEED,
        'assertions':checks,'periodic_oracle_fixtures':fixtures,
        'simulated_quantum_recovery_trials':simulations,
        'reversible_gate_operations_generated':mixer_gates_total,
        'max_input_bits_checked':7,
        'simon_queries_for_2^-129_union_bound':'b+128',
        'scope':'finite checks of Simon promise, coherent measurement law, classical simulation of samples; not a QPT proof, native signing implementation or security test',
        'generic_grover_budget_examples':security_examples}
print(json.dumps(result,sort_keys=True,indent=2))
