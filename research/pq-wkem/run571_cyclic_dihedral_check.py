#!/usr/bin/env python3
"""Finite deterministic identities for a directed CYCLIC local seam; no quantum simulation or security proof."""
import hashlib, json, cmath, math

def h(seed, kind, value):
    return int.from_bytes(hashlib.sha256(f'{seed}|{kind}|{value}'.encode()).digest()[:8], 'big')

def mul(u,v,N):
    x,b=u; y,c=v
    return ((x + (y if b==0 else -y))%N, b ^ c)

def main():
    asserted=0; cases=0; right_coset_tests=0; amplitudes=0; known_inverse_attacks=0
    for n in range(2,9):
        N=1<<n
        for seed in range(3):
            A=[h(seed,'A',s) for s in range(N)]
            B=[h(seed,'B',s) for s in range(N)]
            assert len(set(B))==N
            asserted+=1
            inv={v:i for i,v in enumerate(B)}
            for delta in range(1,N):
                F=[A[s]^B[(s+delta)%N] for s in range(N)]
                G=[F[s]^A[s] for s in range(N)]
                cases+=1
                assert G==[B[(s+delta)%N] for s in range(N)]
                asserted+=1
                # The cyclic shift reference is public; knowledge of an inverse of B breaks it immediately.
                assert (inv[G[0]] - 0)%N == delta
                asserted+=1; known_inverse_attacks+=1
                # H generated by reflection h=(-delta,1) with h^2=e.
                refl=((-delta)%N,1)
                assert mul(refl,refl,N)==(0,0)
                asserted+=1
                for x in range(N):
                    for b in (0,1):
                        # O is a single coherent function on the dihedral group.
                        val=B[x] if b==0 else G[x]
                        z=mul((x,b),refl,N)
                        mate=B[z[0]] if z[1]==0 else G[z[0]]
                        assert val==mate
                        asserted+=1; right_coset_tests+=1
                        # Injectivity: any other matching oracle input must be this pair.
                        # This follows logically from B injection; do not enumerate each pair.
                for k in {0,1,2,N//2,N-1}:
                    # Fourier components of |x,0>+|x-delta,1> from the coset x=0.
                    a0=1+0j
                    a1=cmath.exp(2j*math.pi*k*((-delta)%N)/N)
                    expected=cmath.exp(-2j*math.pi*k*delta/N)
                    assert abs(a1/a0-expected)<1e-10
                    asserted+=1; amplitudes+=1
    result={"run":571,"status":"PASS","assertions":asserted,"finite_instances":cases,"right_coset_checks":right_coset_tests,"Fourier_phase_checks":amplitudes,"known_inverse_control_checks":known_inverse_attacks,"max_n_bits_tested":8,"scope":"Algebraic embedding into dihedral HSP and phase identities only; no QPT algorithm executed","QPT_release_security":False,"actual_witness_KEM":False}
    print(json.dumps(result, indent=2, sort_keys=True))
if __name__=='__main__': main()
